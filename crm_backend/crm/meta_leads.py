"""Meta Lead Ads (instant forms) -> CRM. Graph API client, field mapping and idempotent lead creation.

Never log PII: only leadgen ids and counts."""
import hashlib
import hmac
import logging
import time
from datetime import datetime, timedelta, timezone as dt_timezone

import requests
from django.conf import settings
from django.db import IntegrityError, transaction
from django.utils import timezone

from . import services
from .models import Lead, LeadSource, LeadStatus, Note

log = logging.getLogger(__name__)

LEAD_FIELDS = "created_time,field_data,form_id,ad_id,ad_name,adset_id,adset_name,campaign_id,campaign_name,platform,is_organic"
QUESTION_LABELS = {  # normalised question label -> Lead field
    "which treatment are you interested in": "treatment_interest",
    "when would you like to start": "start_timeframe",
}
CLOSED = [LeadStatus.CONVERTED, LeadStatus.LOST, LeadStatus.NOT_INTERESTED, LeadStatus.INVALID]
REPEAT_WINDOW_DAYS = 30
_label_cache: dict[str, dict[str, str]] = {}  # form_id -> {question key: normalised label}


def enabled() -> bool:
    return bool(settings.META_SYSTEM_USER_TOKEN)


def verify_signature(body: bytes, header: str) -> bool:
    """X-Hub-Signature-256 = 'sha256=' + HMAC-SHA256(raw body, app secret)."""
    if not settings.META_APP_SECRET or not header:
        return False
    expected = "sha256=" + hmac.new(settings.META_APP_SECRET.encode(), body, hashlib.sha256).hexdigest()
    return hmac.compare_digest(expected, header)


def graph_get(path: str, params: dict | None = None) -> dict:
    res = requests.get(
        f"https://graph.facebook.com/{settings.META_GRAPH_VERSION}/{path.lstrip('/')}",
        params=params or {},
        headers={"Authorization": f"Bearer {settings.META_SYSTEM_USER_TOKEN}"},  # keep the token out of URLs/logs
        timeout=15,
    )
    if not res.ok:
        log.error("Meta Graph GET %s failed: %s %s", path.split("?")[0], res.status_code, res.text[:200])
        res.raise_for_status()
    return res.json()


def _norm_label(label: str) -> str:
    return " ".join((label or "").lower().replace("?", " ").split())


def question_labels(form_id: str) -> dict[str, str]:
    """Question key -> normalised label, fetched once per form (keys are generated by Meta, labels are what we trust)."""
    if form_id not in _label_cache:
        try:
            data = graph_get(form_id, {"fields": "questions"})
        except requests.RequestException:  # token can't read the form (needs pages_manage_ads): fall back to the field names, which are the question text
            return {}
        _label_cache[form_id] = {q["key"]: _norm_label(q.get("label", "")) for q in data.get("questions", []) if q.get("key")}
    return _label_cache[form_id]


def parse_field_data(field_data: list, labels: dict[str, str]) -> dict:
    values = {f.get("name"): ((f.get("values") or [""])[0] or "").strip() for f in field_data or []}
    out = {
        "name": values.get("full_name") or " ".join(x for x in (values.get("first_name"), values.get("last_name")) if x),
        "email": values.get("email", ""),
        "phone": values.get("phone_number", "").removeprefix("p:"),  # Meta prefixes test-tool numbers with 'p:'
    }
    for key, value in values.items():
        target = QUESTION_LABELS.get(labels.get(key) or _norm_label(key.replace("_", " ")))
        if target and value:
            out[target] = value.replace("_", " ")  # unlabeled/choice answers arrive as snake_case
    return out


def _parse_time(value):
    try:
        return datetime.strptime(value, "%Y-%m-%dT%H:%M:%S%z").astimezone(dt_timezone.utc)
    except (TypeError, ValueError):
        return None


def ingest(data: dict, leadgen_id: str = "") -> tuple[Lead | None, bool, Lead | None]:
    """Create a CRM lead from a Graph lead object. Idempotent on meta_lead_id.
    Returns (lead, created, earlier_lead_if_repeat)."""
    leadgen_id = str(data.get("id") or leadgen_id)
    existing = Lead.objects.filter(meta_lead_id=leadgen_id).first()
    if existing:
        return existing, False, None
    form_id = str(data.get("form_id") or "")
    parsed = parse_field_data(data.get("field_data"), question_labels(form_id) if form_id else {})
    phone = services.normalize_phone(parsed["phone"])
    repeat = None
    if phone:
        repeat = (Lead.objects.alive().filter(phone=phone, created_at__gte=timezone.now() - timedelta(days=REPEAT_WINDOW_DAYS))
                  .exclude(status__in=CLOSED).order_by("created_at").first())
    treatment, timeframe = parsed.get("treatment_interest", ""), parsed.get("start_timeframe", "")
    platform = data.get("platform") or ""
    fields = dict(
        name=parsed["name"] or "Meta lead", email=parsed["email"], phone=parsed["phone"],
        source=LeadSource.META_INSTANT_FORM, status=LeadStatus.NEW,
        chief_complaint="\n".join(x for x in (f"Treatment: {treatment}" if treatment else "", f"Wants to start: {timeframe}" if timeframe else "") if x),
        treatment_interest=treatment[:200], start_timeframe=timeframe[:200],
        utm_source={"ig": "instagram", "fb": "facebook"}.get(platform, "meta"), utm_medium="lead_ad",
        utm_campaign=(data.get("campaign_name") or "")[:200], utm_content=(data.get("ad_name") or "")[:200],
        meta_lead_id=leadgen_id, meta_form_id=form_id,
        meta_ad_id=str(data.get("ad_id") or ""), meta_adset_id=str(data.get("adset_id") or ""), meta_campaign_id=str(data.get("campaign_id") or ""),
        meta_ad_name=(data.get("ad_name") or "")[:255], meta_adset_name=(data.get("adset_name") or "")[:255],
        meta_campaign_name=(data.get("campaign_name") or "")[:255],
        meta_platform=platform[:10], meta_is_organic=data.get("is_organic"),
        meta_created_time=_parse_time(data.get("created_time")), meta_raw=data,
        tags=["repeat-enquiry"] if repeat else [],
    )
    try:
        with transaction.atomic():
            lead, _ = services.create_lead(force=True, **fields)
    except IntegrityError:  # webhook and backfill raced: the other one won
        return Lead.objects.get(meta_lead_id=leadgen_id), False, None
    if repeat:
        Note.objects.create(lead=lead, body=f"Repeat enquiry: an open lead with this phone already exists (#{repeat.pk}, {repeat.name}, created {timezone.localtime(repeat.created_at):%d %b %H:%M}).")
    return lead, True, repeat


def fetch_and_ingest(leadgen_id: str):
    if Lead.objects.filter(meta_lead_id=str(leadgen_id)).exists():
        return Lead.objects.get(meta_lead_id=str(leadgen_id)), False, None
    return ingest(graph_get(str(leadgen_id), {"fields": LEAD_FIELDS}), str(leadgen_id))


def iter_form_leads(form_id: str, since_unix: int):
    """All leads of a form created after `since_unix`, following Graph paging."""
    params = {
        "fields": "id," + LEAD_FIELDS, "limit": 100,
        "filtering": '[{"field":"time_created","operator":"GREATER_THAN","value":%d}]' % since_unix,
    }
    data = graph_get(f"{form_id}/leads", params)
    while True:
        yield from data.get("data", [])
        nxt = data.get("paging", {}).get("next")
        if not nxt:
            return
        res = requests.get(nxt, headers={"Authorization": f"Bearer {settings.META_SYSTEM_USER_TOKEN}"}, timeout=15)
        res.raise_for_status()
        data = res.json()


def backfill(since_unix: int | None = None) -> dict:
    """Import leads the webhook missed. Default window: since the newest known Meta lead (minus 1h), at most 7 days back."""
    if since_unix is None:
        newest = Lead.objects.exclude(meta_created_time=None).order_by("-meta_created_time").values_list("meta_created_time", flat=True).first()
        floor = int(time.time()) - 7 * 86400
        since_unix = max(int(newest.timestamp()) - 3600, floor) if newest else floor
    created = seen = 0
    for form_id in settings.META_LEAD_FORM_IDS:
        for data in iter_form_leads(form_id, since_unix):
            seen += 1
            lead, was_created, repeat = ingest(data)
            if was_created:
                created += 1
                from .tasks import notify_meta_lead

                notify_meta_lead(lead.id, bool(repeat))
    return {"seen": seen, "created": created}
